#!/usr/bin/env python3
"""Generate src/render/bigfont.inc: the bold 12-row menu font used by text_draw_big().

Glyph art is rows from the top; cap/ascender top = row 0, x-height top = row 3,
baseline below row 9, descenders rows 10-11.  Variable width, 1 px gap.

    python3 tools/gen_bigfont.py
"""
from pathlib import Path

H = 12
G = {}
def g(ch, top, rows):
    w = len(rows[0]); assert all(len(r) == w for r in rows), ch
    G[ch] = (w, ["." * w] * top + rows + ["." * w] * (H - top - len(rows)))
    assert len(G[ch][1]) == H, (ch, len(G[ch][1]))

g('N', 0, ["##..##", "###.##", "###.##", "######", "##.###", "##.###", "##..##", "##..##", "##..##", "##..##"])
g('H', 0, ["##..##"] * 4 + ["######"] * 2 + ["##..##"] * 4)
g('I', 0, ["######"] + ["..##.."] * 8 + ["######"])
g('S', 0, [".####.", "##..##", "##....", "##....", ".####.", "..####", "....##", "....##", "##..##", ".####."])
g('a', 3, [".####.", "....##", ".#####", "##..##", "##..##", "##..##", ".#####"])
g('c', 3, [".####.", "##..##", "##....", "##....", "##....", "##..##", ".####."])
g('e', 3, [".####.", "##..##", "##..##", "######", "##....", "##..##", ".####."])
g('g', 3, [".#####", "##..##", "##..##", "##..##", "##..##", ".#####", "....##", "##..##", ".####."])
g('h', 0, ["##...."] * 3 + ["#####."] + ["##..##"] * 6)
g('i', 0, ["##", "##", "..", "##", "##", "##", "##", "##", "##", "##"])
g('l', 0, ["##"] * 10)
g("m", 3, ["########"] + ["##.##.##"] * 6)
g('n', 3, ["#####."] + ["##..##"] * 6)
g('o', 3, [".####."] + ["##..##"] * 5 + [".####."])
g('r', 3, ["##.###", "###.##"] + ["##...."] * 5)
g('s', 3, [".#####", "##....", "##....", ".####.", "....##", "....##", "#####."])
g('t', 1, [".##..", ".##..", "#####", ".##..", ".##..", ".##..", ".##..", ".##..", "..###"])
g('u', 3, ["##..##"] * 6 + [".#####"])
g('w', 3, ["##....##", "##....##", "##....##", "##.##.##", "##.##.##", "########", ".##..##."])

order = sorted(G)
out = ["/* GENERATED by tools/gen_bigfont.py — do not edit. */",
       "/* chars: %s */" % "".join(order),
       'static const char BIG_CHARS[] = "%s";' % "".join(order),
       "static const uint8_t BIG_W[] = {%s};" % ", ".join(str(G[c][0]) for c in order),
       "static const uint8_t BIG_ROWS[][%d] PROGMEM = {" % H]
for c in order:
    w, rows = G[c]
    out.append("    /* %s */ {%s}," % (c, ", ".join("0x%02X" % int(r.replace('#', '1').replace('.', '0'), 2) for r in rows)))
out.append("};")
(Path(__file__).resolve().parent.parent / "src" / "render" / "bigfont.inc").write_text("\n".join(out) + "\n")
print("glyphs:", "".join(order))
