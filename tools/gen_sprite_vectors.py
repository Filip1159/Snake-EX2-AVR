#!/usr/bin/env python3
"""Independent second transcription of the b.java sprite selection, used to generate
test/host/sprite_vectors.inc for test_snake_sprites.cpp. Run: python3 tools/gen_sprite_vectors.py
Table-driven (not copied from the C code); source: b.java lines ~470-760, 1326-1392."""
from pathlib import Path

U, L, D, R = 1, 2, 4, 8
BASE = {R: 0, L: 1, U: 2, D: 5}
CORNER = {  # (dir_cur | dir_next) -> {next_dir: sprite}, else default
    3: (L, 7, 8), 9: (R, 6, 9), 6: (L, 9, 6), 12: (R, 8, 7)}
FAT = {7: 19, 6: 18, 9: 21, 8: 20, 2: 14, 5: 17, 1: 13, 0: 12}
CCW = {26: 27, 29: 28, 19: 23, 18: 22, 14: 15, 17: 16, 7: 11, 6: 10, 2: 3, 5: 4}
TAIL = {U: 26, D: 29, L: 25, R: 24}
# turn flag: (prev_dir, new_dir) -> flag ; same dir inherits
TURN = {(L, U): 0x20, (R, U): 0x40, (L, D): 0x40, (R, D): 0x20,
        (U, L): 0x40, (D, L): 0x20, (U, R): 0x20, (D, R): 0x40}


def finish(cur, s):
    if cur & 0x10:
        s = FAT.get(s, s)
    if (cur & 0x60) == 0x40:
        s = CCW.get(s, s)
    return s


def body(cur, nxt):
    s = BASE[cur & 15]
    m = (cur | nxt) & 15
    if m in CORNER:
        d, a, b = CORNER[m]
        s = a if (nxt & 15) == d else b
    return finish(cur, s)


def tail(cur, nxt):
    return finish(cur, TAIL[nxt & 15])


def head(cur, open_):
    d, cw = cur & 15, (cur & 0x60) == 0x20
    tbl = {
        (U, False): (32, -3, -3) if cw else (33, 0, -3),
        (U, True): (38, -4, -5) if cw else (39, -1, -5),
        (D, False): (35, 0, 0) if cw else (34, -3, 0),
        (D, True): (41, -1, 0) if cw else (40, -4, 0),
        (L, False): (31, -3, -1), (L, True): (37, -5, -2),
        (R, False): (30, 0, -1), (R, True): (36, 0, -2)}
    return tbl[(d, open_)]


dirs = (U, L, D, R)
lines = []
for cur in (d | f | g for d in dirs for f in (0, 0x20, 0x40) for g in (0, 0x10)):
    for nxt in (d | f for d in dirs for f in (0, 0x20, 0x40)):
        if (cur & 15) | (nxt & 15) in (5, 10):   # reversal impossible
            continue
        lines.append(f"    {{0x{cur:02X}, 0x{nxt:02X}, {body(cur, nxt)}, {tail(cur, nxt)}}},")
heads = []
for cur in (d | f for d in dirs for f in (0, 0x20, 0x40)):
    for o in (0, 1):
        i, dx, dy = head(cur, bool(o))
        heads.append(f"    {{0x{cur:02X}, {o}, {i}, {dx}, {dy}}},")
turns = []
for pd in dirs:
    for pf in (0, 0x20, 0x40):
        for nd in dirs:
            if (pd | nd) in (5, 10):
                continue
            f = (pf if pd == nd else TURN[(pd, nd)])
            turns.append(f"    {{0x{pd | pf:02X}, {nd}, 0x{nd | f:02X}}},")
out = ["/* GENERATED by tools/gen_sprite_vectors.py — do not edit. */",
       "static const struct { uint8_t cur, next, body, tail; } BODY_V[] = {", *lines, "};",
       "static const struct { uint8_t cur, open, id; int8_t dx, dy; } HEAD_V[] = {", *heads, "};",
       "static const struct { uint8_t prev, nd, expect; } TURN_V[] = {", *turns, "};", ""]
Path(__file__).resolve().parent.parent.joinpath("test/host/sprite_vectors.inc").write_text("\n".join(out))
print(len(lines), "body/tail,", len(heads), "head,", len(turns), "turn vectors")
