#!/usr/bin/env python3
"""Extract the Series 40 status bar (antenna, signal bars, battery, no-SIM mark, "Silent",
clock) from Nokia-GUI4.jpg into src/assets/statusbar.{h,cpp} as a transparent 4 bpp sprite.

Pixels that differ from the reconstructed wallpaper (tools/gen_wallpaper.py) are the icons and
text; everything else stays transparent, so the bar can be drawn on any background.

    python3 tools/gen_statusbar.py        # needs numpy + opencv-python-headless
"""
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_wallpaper                                       # noqa: E402
from gen_assets import fmt, rgb565                         # noqa: E402

THRESHOLD = 75      # colour distance from the wallpaper that counts as ink
ROWS = 13           # the bar lives in rows 1..12; row 0 and columns 0-1 are screen border
MIN_AREA = 3        # drop JPEG speckles smaller than this
COLORS = 15         # + 1 transparent


def main():
    bg = gen_wallpaper.reconstruct().astype(np.float64)
    im = cv2.imread(str(ROOT / "Nokia-GUI4.jpg"))
    dist = np.sqrt(((im.astype(np.float64) - bg) ** 2).sum(2))
    mask = dist > THRESHOLD
    mask[0, :] = False
    mask[:, :2] = False
    mask[ROWS:] = False
    n, lab, stats, _ = cv2.connectedComponentsWithStats(mask.astype(np.uint8), connectivity=8)
    for i in range(1, n):
        if stats[i, cv2.CC_STAT_AREA] < MIN_AREA:
            mask[lab == i] = False

    ys, xs = np.nonzero(mask)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    w, h = int(x1 - x0), int(y1 - y0)
    m = mask[y0:y1, x0:x1]
    rgb = cv2.cvtColor(im[y0:y1, x0:x1], cv2.COLOR_BGR2RGB)

    samples = rgb[m].astype(np.float32)
    cv2.setRNGSeed(1)
    _, labels, centers = cv2.kmeans(samples, COLORS, None,
                                    (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 50, 0.1),
                                    5, cv2.KMEANS_PP_CENTERS)
    pal = [rgb565(*(int(round(v)) for v in c)) for c in centers] + [0]
    idx = np.full((h, w), COLORS, np.uint8)
    idx[m] = labels.reshape(-1)

    flat = idx.reshape(-1).tolist()
    if len(flat) % 2:
        flat.append(COLORS)
    packed = [(flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2)]

    (ROOT / "src" / "assets" / "statusbar.cpp").write_text(f"""/* GENERATED by tools/gen_statusbar.py from Nokia-GUI4.jpg — do not edit. */
#include "assets/statusbar.h"

static const uint16_t PAL_STATUSBAR[16] PROGMEM = {{
{fmt(pal, 4, 12)}
}};
static const uint8_t PIX_STATUSBAR[{len(packed)}] PROGMEM = {{
{fmt(packed, 2, 16)}
}};

const spr_t SPR_STATUSBAR PROGMEM = {{{w}, {h}, {COLORS}, PAL_STATUSBAR, PIX_STATUSBAR}};
""")
    (ROOT / "src" / "assets" / "statusbar.h").write_text(f"""/* Series 40 status bar sprite, generated by tools/gen_statusbar.py. */
#ifndef ASSETS_STATUSBAR_H
#define ASSETS_STATUSBAR_H
#include "assets/assets_gen.h"

#define STATUSBAR_X {int(x0)}      /* top-left of the sprite on screen */
#define STATUSBAR_Y {int(y0)}

extern const spr_t SPR_STATUSBAR PROGMEM;
#endif
""")
    print(f"{w}x{h} at ({x0},{y0}), {len(packed)} bytes")


if __name__ == "__main__":
    main()
