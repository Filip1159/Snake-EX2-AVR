#!/usr/bin/env python3
"""Extract the Series 40 status bar (antenna, signal bars, battery, no-SIM mark, "Silent",
clock) from Nokia-GUI4.jpg into src/assets/statusbar.{h,cpp} as a transparent 4 bpp sprite.

The muted-note icon and "Silent" are a separate sprite (SPR_SILENT), shown only with sound off.

Pixels that differ from the reconstructed wallpaper (tools/gen_wallpaper.py) are the icons and
text; everything else stays transparent, so the bar can be drawn on any background.

    python3 tools/gen_statusbar.py        # needs numpy + opencv-python-headless
"""
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_wallpaper                                       # noqa: E402
from asset_util import fmt, rgb565                         # noqa: E402

THRESHOLD = 75      # colour distance from the wallpaper that counts as ink
ROWS = 13           # the bar lives in rows 1..12; row 0 and columns 0-1 are screen border
MIN_AREA = 3        # drop JPEG speckles smaller than this
COLORS = 15         # + 1 transparent
SILENT_X0, SILENT_X1 = 46, 91   # columns of the muted-note icon and "Silent"


def main():
    bg = gen_wallpaper.reconstruct().astype(np.float64)
    im = cv2.imread(str(ROOT / "tools" / "img" / "Nokia-GUI4.jpg"))
    dist = np.sqrt(((im.astype(np.float64) - bg) ** 2).sum(2))
    mask = dist > THRESHOLD
    mask[0, :] = False
    mask[:, :2] = False
    mask[ROWS:] = False
    n, lab, stats, _ = cv2.connectedComponentsWithStats(mask.astype(np.uint8), connectivity=8)
    for i in range(1, n):
        if stats[i, cv2.CC_STAT_AREA] < MIN_AREA:
            mask[lab == i] = False

    silent = mask.copy()                      # the muted-note icon and "Silent": drawn only when sound is off
    silent[:, :SILENT_X0] = False
    silent[:, SILENT_X1:] = False
    mask &= ~silent

    out_cpp = '/* GENERATED by tools/gen_statusbar.py from Nokia-GUI4.jpg — do not edit. */\n#include "assets/statusbar.h"\n'
    out_h = ""
    for name, m_full in (("STATUSBAR", mask), ("SILENT", silent)):
        cpp, h = sprite(name, im, m_full)
        out_cpp += cpp
        out_h += h
    (ROOT / "src" / "assets" / "statusbar.cpp").write_text(out_cpp)
    (ROOT / "src" / "assets" / "statusbar.h").write_text(f"""/* Series 40 status bar sprites, generated by tools/gen_statusbar.py. */
#ifndef ASSETS_STATUSBAR_H
#define ASSETS_STATUSBAR_H
#include "assets/assets_gen.h"

{out_h}#endif
""")


def sprite(name, im, m_full):
    """Crop the mask's bounding box to a transparent 4 bpp sprite; returns (cpp, header) text."""
    ys, xs = np.nonzero(m_full)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    w, h = int(x1 - x0), int(y1 - y0)
    m = m_full[y0:y1, x0:x1]
    rgb = cv2.cvtColor(im[y0:y1, x0:x1], cv2.COLOR_BGR2RGB)

    samples = rgb[m].astype(np.float32)
    k = min(COLORS, len(samples))
    cv2.setRNGSeed(1)
    _, labels, centers = cv2.kmeans(samples, k, None,
                                    (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 50, 0.1),
                                    5, cv2.KMEANS_PP_CENTERS)
    pal = [rgb565(*(int(round(v)) for v in c)) for c in centers]
    pal += [0] * (16 - len(pal))
    idx = np.full((h, w), COLORS, np.uint8)
    idx[m] = labels.reshape(-1)

    flat = idx.reshape(-1).tolist()
    if len(flat) % 2:
        flat.append(COLORS)
    packed = [(flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2)]
    print(f"{name}: {w}x{h} at ({x0},{y0}), {len(packed)} bytes")

    cpp = f"""
static const uint16_t PAL_{name}[16] PROGMEM = {{
{fmt(pal, 4, 12)}
}};
static const uint8_t PIX_{name}[{len(packed)}] PROGMEM = {{
{fmt(packed, 2, 16)}
}};

const spr_t SPR_{name} PROGMEM = {{{w}, {h}, {COLORS}, PAL_{name}, PIX_{name}}};
"""
    h_txt = f"""#define {name}_X {int(x0)}      /* top-left of the sprite on screen */
#define {name}_Y {int(y0)}
extern const spr_t SPR_{name} PROGMEM;

"""
    return cpp, h_txt


if __name__ == "__main__":
    main()
