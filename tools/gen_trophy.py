#!/usr/bin/env python3
"""Extract the 19x21 trophy sprite (original `d`) from the sprite sheet sprites.png
(3x nearest-neighbour upscale, bottom right of the sheet) into src/assets/trophy.cpp.

    python3 tools/gen_trophy.py [sprites.png]        # needs Pillow
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SCALE, X0, Y0, W, H = 3, 1086, 606, 19, 21      # sheet pixel of the sprite's top-left
sheet = Image.open(sys.argv[1] if len(sys.argv) > 1 else ROOT / "tools" / "img" / "sprites.png").convert("RGB")
bg = sheet.getpixel((300, 300))                  # sheet background = transparent colour

px = [sheet.getpixel((X0 + x * SCALE + 1, Y0 + y * SCALE + 1)) for y in range(H) for x in range(W)]
count = {}
for p in px:
    count[p] = count.get(p, 0) + 1
# 4 bpp: merge the rarest colours into their nearest neighbour until 16 remain
while len(count) > 16:
    rare = min((c for c in count if c != bg), key=count.get)
    near = min((c for c in count if c != rare and c != bg),
               key=lambda c: sum((a - b) ** 2 for a, b in zip(c, rare)))
    count[near] += count.pop(rare)
    px = [near if p == rare else p for p in px]
cols = [bg] + [c for c in count if c != bg]
idx = [cols.index(p) for p in px]
idx += [0] if len(idx) % 2 else []
pal = ", ".join("0x%04X" % (((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)) for r, g, b in cols)
pix = [(idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2)]
body = ",\n".join("    " + ", ".join("0x%02X" % v for v in pix[i:i + 16]) for i in range(0, len(pix), 16))
(ROOT / "src" / "assets" / "trophy.cpp").write_text(f"""/* GENERATED by tools/gen_trophy.py from sprites.png — do not edit. */
#include "assets/trophy.h"

static const uint16_t PAL_TROPHY[{len(cols)}] PROGMEM = {{{pal}}};
static const uint8_t PIX_TROPHY[{len(pix)}] PROGMEM = {{
{body}
}};

const spr_t SPR_TROPHY PROGMEM = {{{W}, {H}, 0, PAL_TROPHY, PIX_TROPHY}};
""")
print(len(cols), "colours,", len(pix), "bytes")
