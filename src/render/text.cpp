static const uint8_t *font_glyph(char c) {
    if (c >= 'A' && c <= 'Z') return FONT5x7[c - 'A'];
    if (c >= 'a' && c <= 'z') return FONT5x7[c - 'a'];
    if (c >= '0' && c <= '9') return FONT5x7[26 + (c - '0')];
    if (c == ' ') return FONT5x7[36];
    if (c == '-') return FONT5x7[37];
    if (c == '.') return FONT5x7[38];
    if (c == ':') return FONT5x7[39];
    return FONT5x7[36];   // unknown → space
}

static void draw_glyph(const uint8_t *g, uint8_t x, uint8_t y,
                       uint8_t scale, uint16_t color) {
    for (uint8_t row = 0; row < 7; row++) {
        uint8_t bits = pgm_read_byte(&g[row]);
        for (uint8_t col = 0; col < 5; col++) {
            if (bits & (1 << (4 - col))) {
                st7735_fill_rect(x + (uint8_t)col * scale,
                                 y + (uint8_t)row * scale,
                                 scale, scale, color);
            }
        }
    }
}

void text_draw(uint8_t x, uint8_t y, const char *txt,
               uint8_t scale, uint16_t color) {
    if (!txt || scale == 0) return;
    uint8_t cx = x;
    for (const char *p = txt; *p; p++) {
        draw_glyph(font_glyph(*p), cx, y, scale, color);
        cx += 6 * scale;   // 5px glyph + 1px spacing, scaled
    }
}

void text_draw_p(uint8_t x, uint8_t y, const char *txt_p,
                 uint8_t scale, uint16_t color) {
    if (!txt_p || scale == 0) return;
    uint8_t cx = x;
    for (const char *p = txt_p; pgm_read_byte(p); p++) {
        draw_glyph(font_glyph(pgm_read_byte(p)), cx, y, scale, color);
        cx += 6 * scale;
    }
}

uint8_t text_width(const char *txt, uint8_t scale) {
    if (!txt || scale == 0) return 0;
    uint8_t n = 0;
    while (txt[n]) n++;
    return n ? (uint8_t)((n * 6 - 1) * scale) : 0;
}

uint8_t text_width_p(const char *txt_p, uint8_t scale) {
    if (!txt_p || scale == 0) return 0;
    uint8_t n = 0;
    while (pgm_read_byte(&txt_p[n])) n++;
    return n ? (uint8_t)((n * 6 - 1) * scale) : 0;
}
